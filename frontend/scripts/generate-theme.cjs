/*
 * Generates src/theme.css: CSS custom properties for every Tailwind color scale
 * used by the Studio, in a dark (default) and a light variant.
 *
 * The light variant mirrors each shade (50 <-> 950, 100 <-> 900, ...) so that
 * existing utility classes such as `bg-slate-900` or `text-indigo-300` remain
 * readable on a light background without rewriting every component.
 *
 * Usage: node scripts/generate-theme.cjs
 */
const fs = require('fs');
const path = require('path');
const colors = require('tailwindcss/colors');

const SCALES = ['slate', 'indigo', 'violet', 'emerald', 'amber', 'cyan', 'rose', 'fuchsia'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

// Neutral scale: full mirror. Accent scales: keep mid-tones (500-700) so
// solid buttons keep their brand colors, mirror only the extremes.
const NEUTRAL_MIRROR = {
  50: '950', 100: '900', 200: '800', 300: '700', 400: '600', 500: '500',
  600: '400', 700: '300', 800: '200', 900: '100', 950: '50',
};
const ACCENT_MIRROR = {
  50: '950', 100: '900', 200: '800', 300: '700', 400: '600', 500: '500',
  600: '600', 700: '700', 800: '200', 900: '100', 950: '50',
};

const toRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};

const lines = [];
lines.push('/* AUTO-GENERATED by scripts/generate-theme.cjs — do not edit by hand. */');
lines.push(':root {');
for (const s of SCALES) {
  for (const sh of SHADES) lines.push(`  --c-${s}-${sh}: ${toRgb(colors[s][sh])};`);
}
lines.push('  --c-white: 255 255 255;');
lines.push('  --c-black: 0 0 0;');
lines.push('  color-scheme: dark;');
lines.push('}');
lines.push('');
lines.push('html.light {');
for (const s of SCALES) {
  const map = s === 'slate' ? NEUTRAL_MIRROR : ACCENT_MIRROR;
  for (const sh of SHADES) lines.push(`  --c-${s}-${sh}: ${toRgb(colors[s][map[sh]])};`);
}
lines.push(`  --c-white: ${toRgb(colors.slate['900'])};`);
lines.push('  color-scheme: light;');
lines.push('}');

fs.writeFileSync(path.join(__dirname, '..', 'src', 'theme.css'), lines.join('\n') + '\n');
console.log('Wrote src/theme.css');

