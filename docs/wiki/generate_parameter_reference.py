"""Write docs/wiki/parameter-reference.md from the desktop app's help content.

The app's F1 help reads src/hdd/services/data/wiki.json; this page is generated from
the same file so the two never disagree. Run it after editing wiki.json:

    python docs/wiki/generate_parameter_reference.py

tests/test_wiki.py fails when the page is out of date.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "hdd" / "services" / "data" / "wiki.json"
TARGET = Path(__file__).resolve().parent / "parameter-reference.md"


def _anchor(title: str) -> str:
    """GitHub's heading anchor for ``title``."""
    slug = re.sub(r"[^\w\- ]", "", title.lower()).strip()
    return re.sub(r"\s", "-", slug)


def render(data: dict) -> str:
    lines = [
        "# Parameter reference",
        "",
        "Every parameter, method, output and metric of the pipeline. The desktop app shows the same",
        "text in its Help panel: press **F1** on a field to open its entry.",
        "",
        "<!-- Generated by docs/wiki/generate_parameter_reference.py from src/hdd/services/data/wiki.json. Do not edit by hand. -->",
        "",
        "## Contents",
        "",
    ]
    by_category = {c["key"]: [t for t in data["topics"] if t["category"] == c["key"]] for c in data["categories"]}
    for category in data["categories"]:
        lines.append(f"- [{category['shortLabel']}](#{_anchor(category['shortLabel'])})")
    for category in data["categories"]:
        lines += ["", f"## {category['shortLabel']}", "", category["description"]]
        for topic in by_category[category["key"]]:
            lines += ["", f"### {topic['title']}", ""]
            meta = [f"`{topic['codeKey']}`" if topic.get("codeKey") else None, topic.get("badge")]
            meta = [m for m in meta if m]
            if meta:
                lines += [" · ".join(meta), ""]
            if topic.get("shortSummary"):
                lines += [topic["shortSummary"], ""]
            if topic.get("formula"):
                lines += ["```text", topic["formula"], "```", ""]
            for field, heading in (("scientificBackground", "Background"), ("implementationDetails", "In this implementation"),
                                   ("tuningGuidelines", "Tuning guidelines")):
                if topic.get(field):
                    lines += [f"**{heading}**", ""] + [f"- {item}" for item in topic[field]] + [""]
            if topic.get("sourceFile"):
                lines += [f"Source: `{topic['sourceFile']}`", ""]
            while lines and lines[-1] == "":
                lines.pop()
    return "\n".join(lines) + "\n"


def main() -> int:
    TARGET.write_text(render(json.loads(SOURCE.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
